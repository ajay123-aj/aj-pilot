/**
 * The one-file setup for a blank Ubuntu machine.
 *
 * The Bash itself lives in machine-setup.sh; this fills in its options block
 * from what was ticked in the "Start from a blank machine" guide. Nothing from
 * the panel goes into it but those options — no token, no private key — so the
 * file can be copied around on a USB stick without worrying about it.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const TEMPLATE = fs.readFileSync(path.join(path.dirname(fileURLToPath(import.meta.url)), 'machine-setup.sh'), 'utf8');

/** The on/off choices, their defaults, and the variable each becomes in the script. */
export const SETUP_FLAGS = {
  tools: ['DO_TOOLS', true],
  sleep: ['DO_SLEEP', true],
  lid: ['DO_LID', true],
  screen: ['DO_SCREEN', true],
  wifi: ['DO_WIFI', true],
  wol: ['DO_WOL', true],
  time: ['DO_TIME', true],
  firewall: ['DO_FIREWALL', true],
  web_ports: ['WEB_PORTS', true],
  fail2ban: ['DO_FAIL2BAN', true],
  updates: ['DO_UPDATES', true],
  sudo: ['DO_SUDO', true],
  swap: ['DO_SWAP', true],
  docker: ['DO_DOCKER', false],
};

const ON = new Set(['1', 'true', 'on', 'yes']);
const OFF = new Set(['0', 'false', 'off', 'no']);

/** One SSH public key line — never a private key, never two lines. */
const PUBKEY = /^(ssh-ed25519|ssh-rsa|ecdsa-sha2-nistp(256|384|521)|sk-ssh-ed25519@openssh\.com|sk-ecdsa-sha2-nistp256@openssh\.com) [A-Za-z0-9+/]+={0,3}( [^\r\n'\\]{0,200})?$/;

/** Single-quoted for Bash; every value is validated first, this is the second line of defence. */
const sq = (v) => `'${String(v).replace(/'/g, `'\\''`)}'`;

/** The query string of GET /api/servers/setup-script, checked. */
export function setupOptionsFrom(query = {}) {
  const flags = {};
  for (const [key, [, def]] of Object.entries(SETUP_FLAGS)) {
    const raw = query[key] === undefined ? '' : String(query[key]).toLowerCase();
    if (raw === '') flags[key] = def;
    else if (ON.has(raw)) flags[key] = true;
    else if (OFF.has(raw)) flags[key] = false;
    else return { error: `"${key}" must be on or off` };
  }

  const sshPort = query.ssh_port === undefined || query.ssh_port === '' ? 22 : Number(query.ssh_port);
  if (!Number.isInteger(sshPort) || sshPort < 1 || sshPort > 65535) return { error: 'The SSH port must be between 1 and 65535' };

  const screenMinutes = query.screen_minutes === undefined || query.screen_minutes === '' ? 1 : Number(query.screen_minutes);
  if (!Number.isInteger(screenMinutes) || screenMinutes < 1 || screenMinutes > 60) return { error: 'The screen timeout must be 1 to 60 minutes' };

  const timezone = String(query.timezone || '').trim();
  if (timezone && !/^[A-Za-z][A-Za-z0-9_+-]*(\/[A-Za-z0-9_+-]+){0,2}$/.test(timezone)) return { error: `"${timezone.slice(0, 40)}" is not a time zone like Asia/Kolkata` };

  const hostname = String(query.hostname || '').trim();
  if (hostname && !/^[A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?$/.test(hostname)) {
    return { error: 'The machine name may use letters, numbers and dashes (up to 63), not starting or ending with a dash' };
  }

  const user = String(query.user || '').trim();
  if (user && !/^[a-z_][a-z0-9_-]{0,31}$/.test(user)) return { error: `"${user.slice(0, 40)}" is not a Linux user name` };

  const sshKey = String(query.ssh_key || '').trim().replace(/\s+/g, ' ');
  if (sshKey && /PRIVATE KEY/.test(sshKey)) return { error: 'That is a private key — paste the public one (the .pub file) instead' };
  if (sshKey && !PUBKEY.test(sshKey)) return { error: 'That does not look like an SSH public key (one line starting with ssh-ed25519 or ssh-rsa)' };

  return { value: { flags, sshPort, screenMinutes, timezone, hostname, user, sshKey } };
}

/** The finished script for those options. */
export function buildSetupScript(opts, { generatedAt = new Date() } = {}) {
  const lines = [
    `# Generated by AJ Pilot on ${generatedAt.toISOString().slice(0, 16).replace('T', ' ')} UTC.`,
    `SSH_PORT=${sq(opts.sshPort)}`,
    `TIMEZONE=${sq(opts.timezone)}`,
    `NEW_HOSTNAME=${sq(opts.hostname)}`,
    `PANEL_USER=${sq(opts.user)}            # empty: whoever runs it with sudo`,
    `SSH_PUBKEY=${sq(opts.sshKey)}`,
    `SCREEN_MINUTES=${sq(opts.screenMinutes)}`,
    ...Object.entries(SETUP_FLAGS).map(([key, [name]]) => `${name}=${opts.flags[key] ? 1 : 0}`),
  ];
  return TEMPLATE.replace('# @@OPTIONS@@', lines.join('\n')).replace(/\r\n/g, '\n');
}
